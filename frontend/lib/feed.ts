/** Escapes the five XML-significant characters. No dependency for this -
 * RSS's element content is a small, fixed set of characters to escape. */
export function escapeXml(value: string): string {
  return value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&apos;");
}
